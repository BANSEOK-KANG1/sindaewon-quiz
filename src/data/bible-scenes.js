export const SCENE_BY_ID = Object.fromEntries(BIBLE_SCENES.map(s => [s.id, s]));
export const scenesForBook = book => BIBLE_SCENES.filter(s => s.books.includes(book));
// Match the lesson content, never the book title alone or a generic word like "stone".
export function scenesForCard(card) {
 const content = [card.title, card.lead, card.items?.flat(2).join(" ") || ""].join(" ");
 return scenesForBook(card.book).map(scene => ({ scene, score: scene.keywords.filter(word => content.includes(word)).length })).filter(row => row.score > 0).sort((a,b) => b.score-a.score).map(row => row.scene);
}
